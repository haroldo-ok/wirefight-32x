def gen_font(outdir):
    # map ASCII 32..127, unknown glyphs -> '?'
    order = [chr(c) for c in range(32, 127)]

    def glyph_for(ch):
        if ch in FONT:
            return FONT[ch]
        return FONT["W"] if ch.isalpha() else FONT[" "]

    rows = []
    for ch in order:
        g = glyph_for(ch).split("|")
        assert len(g) == 7
        bs = []
        for r in g:
            assert len(r) == 5
            b = 0
            for i, c in enumerate(r):
                if c == "#":
                    b |= 1 << (4 - i)
            bs.append(b)
        rows.append(bs)

    hdr = ["/* auto-generated by tools/gen_data.py - do not edit */",
           "#ifndef WF_FONT_H", "#define WF_FONT_H", "#include <stdint.h>",
           "/* 5x7 font for ASCII 32..126, one byte per row, bits 4..0 left..right */",
           "extern uint8_t wf_font7[95][7];",
           "#endif"]
    src = ["/* auto-generated by tools/gen_data.py - do not edit */",
           '#include "font.h"',
           "uint8_t wf_font7[95][7] = {"]
    for bs in rows:
        src.append("    { " + ",".join(f"0x{b:02x}" for b in bs) + " },")
    src.append("};\n")
    (outdir / "font.h").write_text("\n".join(hdr) + "\n")
    (outdir / "font.c").write_text("\n".join(src))
    print(f"font: {len(rows)} glyphs")


def main():
    npz = Path(sys.argv[1])
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    gen_motions(npz, outdir)
    gen_sintab(outdir)
    gen_font(outdir)
    print("OK")


if __name__ == "__main__":
    main()
